/*
 * CAT S22 Flip: cover clock drawn by the kernel.
 *
 * With the lid closed the AP suspends and nothing in Android redraws the
 * cover: ACTION_TIME_TICK is a non-wakeup alarm, so the S22Cover clock would
 * stop until something else wakes the phone.  Here the kernel owns the clock
 * digits instead.  S22Cover hides its clock TextView (INVISIBLE, layout kept)
 * and writes through /sys/module/s22_kclock/parameters/config the rectangle
 * the clock owns, the text anchor and the local time rules:
 *
 *   1 x y w h cx baseline h24 0xRRGGBB utc_off next_utc next_off
 *   0                                   (disable, S22Cover draws again)
 *
 * Every frame sent to the cover is composited here: the clock area of the
 * incoming frame is kept as background and the digits are blended over it,
 * so frames from Android always carry the current time.  An ALARM_REALTIME
 * wakeup at each minute redraws only that rectangle with a CASET/RASET/RAMWR
 * window over SPI (~2 KB instead of a 32 KB frame) and Android has nothing
 * to draw.  This runs whatever the lid state: S22Cover keeps the cover lit
 * with the lid open too (03-10-2026).
 *
 * Autonomous mode (stock-stable-3), for ROMs without a cover app (a GSI):
 * until a cover app writes the config node, and while autonomous=Y, the
 * kernel owns the cover ("active"):
 *  - Android's power on/off of fb2 only change Android's own view (they
 *    return success and keep the frame notifier as usual), its frames and
 *    pans are kept in front_buf but never sent over SPI, and its
 *    lcd-backlight2 writes never reach the backlight GPIO.  This removes
 *    the mirror of the main display Android puts on a secondary display
 *    with no content of its own.
 *  - Lid open: panel off (no power), backlight 0.
 *  - Lid closed: the kernel powers the panel like mdss_spi_display_on(),
 *    sends one black frame and draws HH:MM, the date ("SAT 10 OCT") and the
 *    battery ("85%", bolt while charging), redrawn in the same minute alarm
 *    as above (no other wakeup).  Backlight auto_bl_secs after the lid
 *    closes and after a side key (volume, orange), then off.
 *  - A cover app registering (S22Cover starts after the kernel, or comes
 *    back) or autonomous=N hands the cover back: if Android has it on, a
 *    full power on, Android's last frame and Android's backlight level; if
 *    off, the panel goes off.  From then on it is the v22c/stock-stable-2
 *    client path and the kernel never takes the cover again (until reboot).
 * Local time is sys_tz, which Android sets at boot, on zone changes and at
 * every local midnight; between a DST change and the next of those the EU
 * or US rule (auto from the offset) adds the hour.
 *
 * Every SPI transfer of this file runs in the one freezable work (kc_tick)
 * under kc.lock -> ctrl->spi_tx_mutex, after mdss_spi_wait_tx_done(), and
 * only with kc_panel_on() for drawing (04-10-2026 hang).  Android's power
 * on/off take kc.lock only to decide, and nothing changes hands while
 * Android's own power sequence runs (android_busy).  The hall work never
 * takes kc.lock.
 *
 * The alarm targets minute + KC_LAG_S.  alarmtimer_suspend() programs the
 * PMIC RTC from a second-truncated read and rtc_timer_start() truncates
 * again, so the RTC fires up to 2 s early; a wakeup alarm closer than 2 s
 * makes alarmtimer_suspend() refuse to suspend and hold the system awake
 * for 2 s.  Waking with up to 2 s of lag and redrawing from PM_POST_SUSPEND
 * (minute already changed, alarm re-armed for the next minute) avoids that
 * window: the digits change 0-2 s after the minute.  The redraw itself is
 * queued (kc_queue_tick), never done in the notifier.
 *
 * Glyphs: s22_kclock_font.h, Roboto Regular (clock at the S22Cover clock
 * size, small font for the autonomous date and battery), generated by
 * cat-s22-rom/tools/kclock-font-gen.py.  Pure logic: s22_kclock_logic.h.
 */

