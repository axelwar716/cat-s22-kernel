/*
 * CAT S22 Flip: cover clock drawn by the kernel.
 *
 * With the lid closed the AP suspends and nothing in Android redraws the
 * cover: ACTION_TIME_TICK is a non-wakeup alarm, so the S22Cover clock would
 * stop until something else wakes the phone.  Here the kernel owns the clock
 * digits instead.  S22Cover hides its clock TextView (INVISIBLE, layout kept)
 * and writes through /sys/module/s22_kclock/parameters/config the rectangle
 * the clock owns, the text anchor and the local time rules:
 *
 *   1 x y w h cx baseline h24 0xRRGGBB utc_off next_utc next_off
 *   0                                   (disable, S22Cover draws again)
 *
 * Every frame sent to the cover is composited here: the clock area of the
 * incoming frame is kept as background and the digits are blended over it,
 * so frames from Android always carry the current time.  An ALARM_REALTIME
 * wakeup at each minute redraws only that rectangle with a CASET/RASET/RAMWR
 * window over SPI (~2 KB instead of a 32 KB frame) and Android has nothing
 * to draw.  This runs whatever the lid state: S22Cover keeps the cover lit
 * with the lid open too (03-10-2026).
 *
 * Autonomous mode (stock-stable-2), for ROMs without a cover app (a GSI):
 * while nothing has ever written the config node (no client), the lid is
 * closed and Android has the cover off, the kernel owns the cover.  When
 * Android turns the cover off with the lid closed the panel is kept powered
 * (mdss_spi_display_off() becomes a no-op); when the lid closes with the
 * cover already off the kernel powers it up like mdss_spi_display_on().
 * It then sends one black frame and redraws a centred clock each minute
 * with the same alarm and partial update as above.  The backlight is lit
 * for auto_bl_secs after the kernel takes the cover and after a side key
 * (volume, orange), then turned off, as the stock cover did.  Android
 * turning the cover on takes it back through the normal full power on;
 * opening the lid with Android still off powers the panel off the way
 * Android had asked.  Local time is sys_tz, which Android sets at boot, on
 * zone changes and at every local midnight; between a DST change and the
 * next of those the EU or US rule (auto from the offset) adds the hour.
 * Android drawing to the cover (lid open, or a GSI mirroring the main
 * display) is never touched: frames only flow while Android has it on.
 *
 * The alarm targets minute + KC_LAG_S.  alarmtimer_suspend() programs the
 * PMIC RTC from a second-truncated read and rtc_timer_start() truncates
 * again, so the RTC fires up to 2 s early; a wakeup alarm closer than 2 s
 * makes alarmtimer_suspend() refuse to suspend and hold the system awake
 * for 2 s.  Waking with up to 2 s of lag and redrawing from PM_POST_SUSPEND
 * (minute already changed, alarm re-armed for the next minute) avoids that
 * window: the digits change 0-2 s after the minute.  The redraw itself is
 * queued (kc_queue_tick), never done in the notifier.
 *
 * Lock order: kc.lock -> ctrl->spi_tx_mutex.  mdss_spi_display_on/off take
 * kc.lock only to hand the cover over, never across their panel sequence.
 *
 * Glyphs: s22_kclock_font.h, Roboto Regular at the S22Cover clock size,
 * generated by cat-s22-rom/tools/kclock-font-gen.py.
 */

