#define KC_MAX_PIX	(128 * 64)
#define KC_LAG_S	2
#define KC_CMD_CASET	0x2a
#define KC_CMD_RASET	0x2b
#define KC_CMD_RAMWR	0x2c
#define KC_AUTO_H	32		/* autonomous clock band, centred */

/* when userspace last set sys_tz (kernel/time/time.c) */
extern time64_t s22_sys_tz_set;

static bool kc_autonomous = true;
static bool kc_auto_h24 = true;
static int kc_auto_bl_secs = 8;
static int kc_dst = -1;			/* -1 auto, 0 off, 1 EU, 2 US */

static struct s22_kclock {
	struct mutex lock;
	struct spi_panel_data *ctrl;
	int xres, yres;
	u16 col0, col1, row0, row1;	/* full window from the panel on-cmds */
	bool window_ok;

	bool enabled;
	int x, y, w, h;			/* rectangle owned by the clock */
	int cx, base;			/* text centre x, baseline y */
	bool h24;
	u16 color;
	s64 off, next_utc, next_off;	/* local = utc + off (next_off from next_utc) */

	u16 *bg;			/* clock area of the last frame */
	bool bg_valid;
	u16 *pix;			/* rectangle sent over SPI */
	u16 *full;			/* black frame (autonomous take-over) */
	u8 *cmd;			/* DMA-safe command and parameters */
	s64 shown;			/* local minute on the panel, -1 = none */
	bool lid_open;
	int lid_changes;		/* real lid changes since boot */
	bool lid_seen;			/* the hall probe reported once */
	bool suspending;		/* between PM_SUSPEND_PREPARE and POST */

	/* autonomous mode */
	bool client;			/* the config node was written */
	bool android_on;		/* Android has the cover on */
	bool android_seen;		/* Android turned it on or off once */
	bool android_busy;		/* inside Android's own power off */
	bool own;			/* the kernel drives the cover */
	bool full_pending;		/* send the black frame first */
	bool light_pending;		/* light the backlight after drawing */
	bool bl_lit;
	struct delayed_work bl_work;
	struct work_struct key_work;
	struct wakeup_source *ws_bl;
	struct input_handler key_handler;

	struct alarm alarm;
	struct work_struct work;
	struct wakeup_source *ws;
	struct notifier_block pm_nb;
	bool ready;			/* buffers, alarm and wakeup source set up */

	u32 n_frames, n_partial, n_same, n_nobg, n_off, n_err, n_alarm, n_resume;
	u32 n_keep, n_take, n_yield, n_release, n_keys;
} kc = {
	.lock = __MUTEX_INITIALIZER(kc.lock),
	.shown = -1,
	.lid_open = true,
	.color = 0xffff,
};

static int kc_weekday(time64_t t)
{
	return ((u32)div_s64(t, 86400) + 4) % 7;	/* 0 = Sunday */
}

/* UTC instant of hour:00 on the nth Sunday of mon (nth 0 = last). */
static time64_t kc_sunday(int year, int mon, int nth, int hour)
{
	static const u8 mdays[13] = { 0, 31, 28, 31, 30, 31, 30, 31, 31, 30,
				      31, 30, 31 };
	int day;

	if (nth > 0)
		day = 1 + (7 - kc_weekday(mktime64(year, mon, 1, 0, 0, 0))) % 7 +
			(nth - 1) * 7;
	else
		day = mdays[mon] -
			kc_weekday(mktime64(year, mon, mdays[mon], 0, 0, 0));
	return mktime64(year, mon, day, hour, 0, 0);
}

/* 1 if t is in summer time: EU 01:00 UTC last Sunday Mar-Oct; US 02:00
 * local second Sunday Mar - first Sunday Nov (std = standard offset). */
static int kc_summer(int rule, time64_t t, int std)
{
	struct tm tm;
	int y;

	time64_to_tm(t, 0, &tm);
	y = tm.tm_year + 1900;
	if (rule == 1)
		return t >= kc_sunday(y, 3, 0, 1) && t < kc_sunday(y, 10, 0, 1);
	return t >= kc_sunday(y, 3, 2, 2) - std &&
		t < kc_sunday(y, 11, 1, 2) - std - 3600;
}

/* Local time for the autonomous clock: sys_tz plus the DST hour Android
 * has not applied yet (it only sets the zone at boot, zone change and
 * local midnight). */
static s64 kc_auto_local(time64_t now)
{
	int off = -sys_tz.tz_minuteswest * 60;
	time64_t set = READ_ONCE(s22_sys_tz_set);
	int rule = READ_ONCE(kc_dst), std = off, d = 0;

	if (rule < 0)
		rule = off >= 0 && off <= 3 * 3600 ? 1 :
			off >= -10 * 3600 && off <= -4 * 3600 ? 2 : 0;
	if (rule > 2)
		rule = 0;
	if (rule && set > 0 && set <= now) {
		if (rule == 2 && kc_summer(2, set, off))
			std = off - 3600;
		d = kc_summer(rule, now, std) - kc_summer(rule, set, std);
	}
	return now + off + d * 3600;
}

static s64 kc_local_minute(void)
{
	s64 t = ktime_get_real_seconds();

	if (kc.own)
		t = kc_auto_local(t);
	else
		t += (kc.next_utc && t >= kc.next_utc) ? kc.next_off : kc.off;
	return t < 0 ? 0 : div_s64(t, 60);
}

static int kc_format(s64 minute, char *s)
{
	u32 day_min, hh, mm;
	int n = 0;

	div_u64_rem(minute, 24 * 60, &day_min);
	hh = day_min / 60;
	mm = day_min % 60;
	if (!kc.h24) {
		hh %= 12;
		if (!hh)
			hh = 12;
	}
	if (kc.h24 || hh >= 10)
		s[n++] = '0' + hh / 10;
	s[n++] = '0' + hh % 10;
	s[n++] = ':';
	s[n++] = '0' + mm / 10;
	s[n++] = '0' + mm % 10;
	return n;
}

static inline u16 kc_blend(u16 b, u16 f, u32 a)
{
	u32 na = 255 - a;
	u32 r = ((b >> 11) * na + (f >> 11) * a + 127) / 255;
	u32 g = (((b >> 5) & 63) * na + ((f >> 5) & 63) * a + 127) / 255;
	u32 bl = ((b & 31) * na + (f & 31) * a + 127) / 255;

	return r << 11 | g << 5 | bl;
}

/* kc.pix = kc.bg with the time blended in; rectangle coordinates. */
static void kc_render(s64 minute)
{
	char s[5];
	int n = kc_format(minute, s), i;
	u32 width64 = 0;
	int pen64;

	memcpy(kc.pix, kc.bg, kc.w * kc.h * 2);
	for (i = 0; i < n; i++)
		width64 += s22_kclock_glyphs[s[i] == ':' ? 10 : s[i] - '0'].adv64;
	pen64 = (kc.cx - kc.x) * 64 - (int)width64 / 2;

	for (i = 0; i < n; i++) {
		const struct s22_kclock_glyph *g =
			&s22_kclock_glyphs[s[i] == ':' ? 10 : s[i] - '0'];
		const u8 *a = s22_kclock_alpha + g->off;
		int gx = DIV_ROUND_CLOSEST(pen64, 64) + g->bx;
		int gy = kc.base - kc.y + g->by;
		int px, py;

		for (py = 0; py < g->h; py++) {
			int ry = gy + py;

			if (ry < 0 || ry >= kc.h)
				continue;
			for (px = 0; px < g->w; px++) {
				int rx = gx + px;
				u32 al = a[py * g->w + px];
				u16 *d;

				if (!al || rx < 0 || rx >= kc.w)
					continue;
				d = &kc.pix[ry * kc.w + rx];
				*d = al == 255 ? kc.color : kc_blend(*d, kc.color, al);
			}
		}
		pen64 += g->adv64;
	}
}

static bool kc_panel_on(struct spi_panel_data *ctrl)
{
	/* mdss_spi_display_on/off track the MDP5 cover with PANEL_ACTIVE;
	 * PANEL_INIT is only used by the panel event handler. */
	return (ctrl->ctrl_state & CTRL_STATE_PANEL_ACTIVE) &&
		ctrl->panel_data.panel_info.panel_power_state ==
			MDSS_PANEL_POWER_ON;
}

static int kc_cmd(struct spi_panel_data *ctrl, u8 c, u16 a, u16 b, bool args)
{
	int rc;

	kc.cmd[0] = c;
	gpio_direction_output(ctrl->disp_dc_gpio, 0);
	rc = mdss_spi_tx_command(kc.cmd);
	gpio_direction_output(ctrl->disp_dc_gpio, 1);
	if (rc || !args)
		return rc;
	kc.cmd[4] = a >> 8;
	kc.cmd[5] = a & 0xff;
	kc.cmd[6] = b >> 8;
	kc.cmd[7] = b & 0xff;
	return mdss_spi_tx_parameter(kc.cmd + 4, 4);
}

/* Caller holds kc.lock and ctrl->spi_tx_mutex, no frame in flight. */
static int kc_send(struct spi_panel_data *ctrl)
{
	int rc;

	rc = kc_cmd(ctrl, KC_CMD_CASET, kc.col0 + kc.x,
		    kc.col0 + kc.x + kc.w - 1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RASET, kc.row0 + kc.y,
			  kc.row0 + kc.y + kc.h - 1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RAMWR, 0, 0, false);
	rc = rc ?: mdss_spi_tx_pixel_sync(kc.pix, kc.w * kc.h * 2);
	/* Frames are bare RAMWR continuations: restore the full window and
	 * leave the write pointer at its start whatever happened above. */
	kc_cmd(ctrl, KC_CMD_CASET, kc.col0, kc.col1, true);
	kc_cmd(ctrl, KC_CMD_RASET, kc.row0, kc.row1, true);
	kc_cmd(ctrl, KC_CMD_RAMWR, 0, 0, false);
	return rc;
}

/* Same conditions as kc_send(): one black frame over the full window. */
static int kc_send_full(struct spi_panel_data *ctrl)
{
	int rc;

	rc = kc_cmd(ctrl, KC_CMD_CASET, kc.col0, kc.col1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RASET, kc.row0, kc.row1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RAMWR, 0, 0, false);
	rc = rc ?: mdss_spi_tx_pixel_sync(kc.full, kc.xres * kc.yres * 2);
	return rc;
}

static void kc_arm_locked(void)
{
	s64 next;

	if (!kc.ready)
		return;
	alarm_try_to_cancel(&kc.alarm);
	if (!kc.enabled && !kc.own)
		return;
	next = (div_s64(ktime_get_real_seconds(), 60) + 1) * 60 + KC_LAG_S;
	alarm_start(&kc.alarm, ktime_set(next, 0));
}

/* Lit for auto_bl_secs (< 0: until the kernel lets the cover go). */
static void kc_light_locked(void)
{
	int secs = READ_ONCE(kc_auto_bl_secs);

	if (!kc.own || !secs)
		return;
	mdss_spi_s22_cover_bl(1);
	kc.bl_lit = true;
	if (secs > 0) {
		/* stay awake so the off work runs on time, not after resume */
		__pm_wakeup_event(kc.ws_bl, secs * 1000 + 500);
		mod_delayed_work(system_wq, &kc.bl_work, secs * HZ);
	}
}

static void kc_bl_off_fn(struct work_struct *work)
{
	mutex_lock(&kc.lock);
	if (kc.own && kc.bl_lit && READ_ONCE(kc_auto_bl_secs) > 0) {
		mdss_spi_s22_cover_bl(0);
		kc.bl_lit = false;
	}
	mutex_unlock(&kc.lock);
}

static void kc_key_fn(struct work_struct *work)
{
	mutex_lock(&kc.lock);
	if (kc.own) {
		kc.n_keys++;
		kc_light_locked();
	}
	mutex_unlock(&kc.lock);
}

static bool kc_auto_allowed_locked(void)
{
	return kc.ready && kc.ctrl && kc.window_ok &&
		READ_ONCE(kc_autonomous) && !kc.client && !kc.lid_open &&
		!kc.android_busy && (kc.android_seen || kc.lid_changes);
}

/* Kernel takes the cover (kc.lock held).  With the panel already on (kept
 * from Android's off) nothing goes over SPI here. */
static int kc_take_locked(struct spi_panel_data *ctrl)
{
	struct mdss_panel_data *pdata = &ctrl->panel_data;
	int rc;

	if (!kc_panel_on(ctrl)) {
		/* as mdss_spi_display_on(), without the frame notifier */
		rc = mdss_spi_panel_power_ctrl(pdata, MDSS_PANEL_POWER_ON);
		if (rc) {
			kc.n_err++;
			pr_err("s22_kclock: cover power on failed %d\n", rc);
			return rc;
		}
		mdss_spi_panel_pinctrl_set_state(ctrl, true);
		mdss_spi_panel_reset(pdata, 1);
		mutex_lock(&ctrl->spi_tx_mutex);
		ctrl->ctrl_state |= CTRL_STATE_PANEL_ACTIVE;
		mdss_spi_panel_on(pdata);
		mutex_unlock(&ctrl->spi_tx_mutex);
	}

	kc.own = true;
	kc.x = 0;
	kc.w = kc.xres;
	kc.h = min(KC_AUTO_H, kc.yres);
	kc.y = (kc.yres - kc.h) / 2;
	kc.cx = kc.xres / 2;
	/* digits are 21 px above the baseline: centre them vertically */
	kc.base = kc.yres / 2 + 10;
	kc.h24 = READ_ONCE(kc_auto_h24);
	kc.color = 0xffff;
	memset(kc.bg, 0, kc.w * kc.h * 2);
	kc.bg_valid = true;
	kc.shown = -1;
	kc.full_pending = true;
	kc.light_pending = true;
	kc.n_take++;
	return 0;
}

/* Kernel lets the cover go (kc.lock held). */
static void kc_release_locked(struct spi_panel_data *ctrl)
{
	struct mdss_panel_data *pdata = &ctrl->panel_data;

	kc.own = false;
	kc.bl_lit = false;
	kc.full_pending = false;
	kc.light_pending = false;
	kc.bg_valid = false;
	kc.shown = -1;
	cancel_delayed_work(&kc.bl_work);
	kc.n_release++;
	if (kc.android_on)
		return;

	/* Android had it off: power it off the way mdss_spi_display_off()
	 * would have (off cmds only after PANEL_INIT, reset lines and
	 * regulators by the lid state). */
	mutex_lock(&ctrl->spi_tx_mutex);
	ctrl->ctrl_state &= ~CTRL_STATE_PANEL_ACTIVE;
	if (ctrl->ctrl_state & CTRL_STATE_PANEL_INIT) {
		mdss_spi_panel_off(pdata);
		ctrl->ctrl_state &= ~CTRL_STATE_PANEL_INIT;
	}
	mutex_unlock(&ctrl->spi_tx_mutex);
	mdss_spi_panel_power_ctrl(pdata, MDSS_PANEL_POWER_OFF);
	mdss_spi_s22_cover_bl(0);
}

static void kc_tick(void)
{
	struct spi_panel_data *ctrl;
	s64 minute;
	int rc;

	mutex_lock(&kc.lock);
	ctrl = kc.ctrl;
	if (!kc.ready || !ctrl)
		goto out;
	if (kc_auto_allowed_locked() && !kc.android_on) {
		if (!kc.own && kc_take_locked(ctrl))
			goto out;
	} else if (kc.own) {
		kc_release_locked(ctrl);
		goto out;
	}
	if (!kc.enabled && !kc.own)
		goto out;
	minute = kc_local_minute();
	if (minute == kc.shown && !kc.full_pending) {
		kc.n_same++;
		goto out;
	}
	if (!kc.bg_valid) {
		kc.n_nobg++;
		goto out;
	}
	kc_render(minute);

	mutex_lock(&ctrl->spi_tx_mutex);
	if (!kc_panel_on(ctrl)) {
		kc.n_off++;
		rc = 1;
	} else if (!mdss_spi_wait_tx_done(ctrl)) {
		rc = -ETIMEDOUT;
	} else {
		rc = kc.full_pending ? kc_send_full(ctrl) : 0;
		rc = rc ?: kc_send(ctrl);
	}
	mutex_unlock(&ctrl->spi_tx_mutex);

	if (!rc) {
		kc.shown = minute;
		kc.full_pending = false;
		kc.n_partial++;
		if (kc.light_pending) {
			kc.light_pending = false;
			kc_light_locked();
		}
	} else if (rc < 0) {
		kc.n_err++;
		pr_err_ratelimited("s22_kclock: partial update failed %d\n", rc);
	}
out:
	kc_arm_locked();
	mutex_unlock(&kc.lock);
}

static void kc_work_fn(struct work_struct *work)
{
	/* Relax first: a tick queued while this one runs keeps the source.
	 * The freezer waits for a running freezable work before suspend. */
	__pm_relax(kc.ws);
	kc_tick();
}

/*
 * Redraws never run in the caller: PM_POST_SUSPEND runs inside pm_suspend()
 * of the suspend HAL thread and the lid in the hall work, and a stuck SPI
 * there blocked suspend, the HAL and system_server (04-10-2026).  The work
 * keeps the wakeup source until it has run; a work already pending relaxes
 * it itself, so a failed queue_work() must not.
 */
static void kc_queue_tick(void)
{
	if (!READ_ONCE(kc.ready))
		return;
	/* inside suspend a held source aborts it; PM_POST_SUSPEND requeues */
	if (!READ_ONCE(kc.suspending))
		__pm_stay_awake(kc.ws);
	/* freezable: runs once devices and the SPI controller are resumed */
	queue_work(system_freezable_wq, &kc.work);
}

static enum alarmtimer_restart kc_alarm_fn(struct alarm *alarm, ktime_t now)
{
	kc.n_alarm++;
	kc_queue_tick();
	return ALARMTIMER_NORESTART;
}

static int kc_pm_notify(struct notifier_block *nb, unsigned long event,
			void *unused)
{
	if (event == PM_SUSPEND_PREPARE) {
		WRITE_ONCE(kc.suspending, true);
	} else if (event == PM_POST_SUSPEND) {
		WRITE_ONCE(kc.suspending, false);
		kc.n_resume++;
		kc_queue_tick();
	}
	return NOTIFY_DONE;
}

void s22_kclock_compose(struct spi_panel_data *ctrl, u16 *frame)
{
	int row;

	if (!READ_ONCE(kc.enabled))
		return;
	mutex_lock(&kc.lock);
	if (kc.ready && kc.enabled && ctrl == kc.ctrl) {
		s64 minute = kc_local_minute();

		for (row = 0; row < kc.h; row++)
			memcpy(kc.bg + row * kc.w,
			       frame + (kc.y + row) * kc.xres + kc.x, kc.w * 2);
		kc.bg_valid = true;
		kc_render(minute);
		for (row = 0; row < kc.h; row++)
			memcpy(frame + (kc.y + row) * kc.xres + kc.x,
			       kc.pix + row * kc.w, kc.w * 2);
		kc.shown = minute;
		kc.n_frames++;
	}
	mutex_unlock(&kc.lock);
}

void s22_kclock_lid(int open)
{
	mutex_lock(&kc.lock);
	/* the hall work reports on every interrupt, the probe at boot */
	if (kc.lid_seen && kc.lid_open != !!open)
		kc.lid_changes++;
	kc.lid_seen = true;
	kc.lid_open = !!open;
	kc_arm_locked();
	mutex_unlock(&kc.lock);
	/* closed: redraw (client) or take the cover; open: let it go */
	if (!open || READ_ONCE(kc.own))
		kc_queue_tick();
}

/*
 * mdss_spi_display_off(): true = the kernel keeps the cover powered and
 * the caller must not turn it off.  Only state changes here, no SPI.
 * false = the caller powers it off and then calls
 * s22_kclock_display_off_done(); until then the work leaves it alone.
 */
bool s22_kclock_display_off(struct spi_panel_data *ctrl)
{
	bool keep;

	mutex_lock(&kc.lock);
	kc.android_on = false;
	kc.android_seen = true;
	keep = ctrl == kc.ctrl && kc_auto_allowed_locked() &&
		kc_panel_on(ctrl) && !kc_take_locked(ctrl);
	if (keep) {
		kc.n_keep++;
		kc_arm_locked();
	} else {
		kc.android_busy = true;
	}
	mutex_unlock(&kc.lock);
	if (keep)
		kc_queue_tick();
	return keep;
}

void s22_kclock_display_off_done(void)
{
	bool tick;

	mutex_lock(&kc.lock);
	kc.android_busy = false;
	/* with a cover app this stays the v22c path: no tick from here */
	tick = !kc.client && !kc.lid_open;
	mutex_unlock(&kc.lock);
	if (tick)
		kc_queue_tick();
}

/* mdss_spi_display_on(): Android takes the cover back (full power on). */
void s22_kclock_display_on(struct spi_panel_data *ctrl)
{
	mutex_lock(&kc.lock);
	kc.android_on = true;
	kc.android_seen = true;
	if (kc.own && ctrl == kc.ctrl) {
		kc.own = false;
		kc.bl_lit = false;
		kc.full_pending = false;
		kc.light_pending = false;
		kc.bg_valid = false;
		kc.shown = -1;
		cancel_delayed_work(&kc.bl_work);
		kc.n_yield++;
		kc_arm_locked();
	}
	mutex_unlock(&kc.lock);
}

/* Backlight writes from Android leave the GPIO alone while this is true. */
bool s22_kclock_owns(void)
{
	return READ_ONCE(kc.own);
}

static bool kc_find_window(struct spi_panel_data *ctrl, u8 c, u16 *a, u16 *b)
{
	int i;

	for (i = 0; i < ctrl->on_cmds.cmd_cnt; i++) {
		struct spi_cmd_desc *d = &ctrl->on_cmds.cmds[i];
			const u8 *p = (const u8 *)d->parameter;

		if ((u8)d->command[0] != c || d->dchdr.dlen != 5)
			continue;
		*a = p[0] << 8 | p[1];
		*b = p[2] << 8 | p[3];
		return true;
	}
	return false;
}

void s22_kclock_attach(struct spi_panel_data *ctrl)
{
	struct mdss_panel_info *pinfo = &ctrl->panel_data.panel_info;

	mutex_lock(&kc.lock);
	kc.ctrl = ctrl;
	kc.xres = pinfo->xres;
	kc.yres = pinfo->yres;
	kc.window_ok = pinfo->bpp == 16 &&
		kc_find_window(ctrl, KC_CMD_CASET, &kc.col0, &kc.col1) &&
		kc_find_window(ctrl, KC_CMD_RASET, &kc.row0, &kc.row1) &&
		kc.col1 - kc.col0 + 1 == kc.xres &&
		kc.row1 - kc.row0 + 1 == kc.yres &&
		kc.xres * kc.yres <= 128 * 128;
	mutex_unlock(&kc.lock);
	pr_info("s22_kclock: cover %dx%d window %u-%u/%u-%u %s\n", kc.xres,
		kc.yres, kc.col0, kc.col1, kc.row0, kc.row1,
		kc.window_ok ? "ok" : "unusable");
}

static int kc_config_set(const char *val, const struct kernel_param *kp)
{
	int en, x, y, w, h, cx, base, h24;
	unsigned int rgb;
	long long off, next_utc, next_off;
	int n;

	n = sscanf(val, "%d %d %d %d %d %d %d %d %x %lld %lld %lld", &en, &x,
		   &y, &w, &h, &cx, &base, &h24, &rgb, &off, &next_utc,
		   &next_off);
	if (n < 1)
		return -EINVAL;

	mutex_lock(&kc.lock);
	if (!kc.ready) {
		mutex_unlock(&kc.lock);
		return -EAGAIN;
	}
	/* a cover app is present: the autonomous mode is over for good */
	kc.client = true;
	if (kc.own && kc.ctrl)
		kc_release_locked(kc.ctrl);
	if (!en) {
		kc.enabled = false;
		goto done;
	}
	if (n != 12 || !kc.ctrl || !kc.window_ok || x < 0 || y < 0 ||
	    w <= 0 || h <= 0 || x + w > kc.xres || y + h > kc.yres ||
	    w * h > KC_MAX_PIX || off < -86400 || off > 86400 ||
	    next_off < -86400 || next_off > 86400) {
		mutex_unlock(&kc.lock);
		return -EINVAL;
	}
	if (!kc.enabled || x != kc.x || y != kc.y || w != kc.w || h != kc.h)
		kc.bg_valid = false;	/* wait for a frame with this layout */
	kc.x = x;
	kc.y = y;
	kc.w = w;
	kc.h = h;
	kc.cx = cx;
	kc.base = base;
	kc.h24 = !!h24;
	kc.color = ((rgb >> 8) & 0xf800) | ((rgb >> 5) & 0x07e0) |
		   ((rgb >> 3) & 0x001f);
	kc.off = off;
	kc.next_utc = next_utc;
	kc.next_off = next_off;
	kc.shown = -1;
	kc.enabled = true;
done:
	kc_arm_locked();
	mutex_unlock(&kc.lock);
	return 0;
}

static int kc_config_get(char *buf, const struct kernel_param *kp)
{
	int n;

	mutex_lock(&kc.lock);
	n = scnprintf(buf, PAGE_SIZE,
		"%d %d %d %d %d %d %d %d 0x%04x %lld %lld %lld | window %s lid %s bg %d shown %lld | frames %u partial %u same %u nobg %u off %u err %u alarm %u resume %u | auto %s client %d android %s own %d bl %d keep %u take %u yield %u release %u keys %u tz %d set %lld\n",
		kc.enabled, kc.x, kc.y, kc.w, kc.h, kc.cx, kc.base, kc.h24,
		kc.color, kc.off, kc.next_utc, kc.next_off,
		kc.window_ok ? "ok" : "unusable",
		kc.lid_open ? "open" : "closed", kc.bg_valid, kc.shown,
		kc.n_frames, kc.n_partial, kc.n_same, kc.n_nobg, kc.n_off,
		kc.n_err, kc.n_alarm, kc.n_resume,
		kc_autonomous ? "on" : "off", kc.client,
		kc.android_on ? "on" : kc.android_seen ? "off" : "unseen",
		kc.own, kc.bl_lit, kc.n_keep, kc.n_take, kc.n_yield,
		kc.n_release, kc.n_keys, -sys_tz.tz_minuteswest,
		(long long)READ_ONCE(s22_sys_tz_set));
	mutex_unlock(&kc.lock);
	return n;
}

