#define KC_MAX_PIX	(128 * 64)
#define KC_LAG_S	2
#define KC_CMD_CASET	0x2a
#define KC_CMD_RASET	0x2b
#define KC_CMD_RAMWR	0x2c

/* when userspace last set sys_tz (kernel/time/time.c) */
extern time64_t s22_sys_tz_set;

static bool kc_autonomous = true;
static bool kc_auto_h24 = true;
static int kc_auto_bl_secs = 8;
static int kc_dst = -1;			/* -1 auto, 0 off, 1 EU, 2 US */

static struct s22_kclock {
	struct mutex lock;
	struct spi_panel_data *ctrl;
	int xres, yres;
	u16 col0, col1, row0, row1;	/* full window from the panel on-cmds */
	bool window_ok;

	/* cover app (client) mode */
	bool enabled;
	int x, y, w, h;			/* rectangle owned by the clock */
	int cx, base;			/* text centre x, baseline y */
	bool h24;
	u16 color;
	s64 off, next_utc, next_off;	/* local = utc + off (next_off from next_utc) */

	u16 *bg;			/* clock area of the last frame */
	bool bg_valid;
	u16 *pix;			/* rectangle sent over SPI */
	u16 *full;			/* black frame (autonomous take-over) */
	u8 *cmd;			/* DMA-safe command and parameters */
	s64 shown;			/* local minute on the panel, -1 = none */
	bool lid_open;			/* written by the hall work, no lock */
	bool suspending;		/* between PM_SUSPEND_PREPARE and POST */

	/* autonomous mode */
	bool client;			/* the config node was written */
	bool active;			/* kernel owns the cover (also under
					 * spi_tx_mutex, read by the kickoff) */
	bool android_on;		/* Android's view of the cover */
	bool android_seen;		/* Android turned it on or off once */
	bool android_busy;		/* Android's real power on/off running */
	bool own;			/* lid closed: the kernel draws */
	bool full_pending;		/* send the black frame first */
	bool light_pending;		/* light the backlight after drawing */
	bool bl_lit;
	struct kc_layout lay;		/* autonomous band and baselines */
	int batt_cap;			/* -1 unknown */
	bool batt_chg;
	u32 batt_min;			/* UTC minute of the last battery read */
	struct delayed_work bl_work;
	struct work_struct key_work;
	struct wakeup_source *ws_bl;
	struct input_handler key_handler;

	struct alarm alarm;
	struct work_struct work;
	struct wakeup_source *ws;
	struct notifier_block pm_nb;
	bool ready;			/* buffers, alarm and wakeup source set up */

	u32 n_frames, n_partial, n_same, n_nobg, n_off, n_err, n_alarm, n_resume;
	u32 n_take, n_release, n_keys;
	u32 n_enter, n_leave, n_von, n_voff, n_swallow;
} kc = {
	.lock = __MUTEX_INITIALIZER(kc.lock),
	.shown = -1,
	.lid_open = true,
	.color = 0xffff,
	.batt_cap = -1,
	.batt_min = U32_MAX,
};

/* Local time for the autonomous clock: sys_tz plus the DST hour Android
 * has not applied yet (s22_kclock_logic.h). */
static s64 kc_auto_local(time64_t now)
{
	return kc_dst_local(now, -sys_tz.tz_minuteswest * 60,
			    READ_ONCE(s22_sys_tz_set), READ_ONCE(kc_dst));
}

static s64 kc_local_minute(void)
{
	s64 t = ktime_get_real_seconds();

	if (kc.own)
		t = kc_auto_local(t);
	else
		t += (kc.next_utc && t >= kc.next_utc) ? kc.next_off : kc.off;
	return t < 0 ? 0 : div_s64(t, 60);
}

static int kc_format(s64 minute, char *s)
{
	u32 day_min;

	div_u64_rem(minute, 24 * 60, &day_min);
	return kc_format_hm(day_min, kc.h24, s);
}

/* kc.pix = kc.bg with the time blended in; rectangle coordinates. */
static void kc_render(s64 minute)
{
	char s[5];
	int n = kc_format(minute, s), i;
	u32 width64 = 0;
	int pen64;

	memcpy(kc.pix, kc.bg, kc.w * kc.h * 2);
	for (i = 0; i < n; i++)
		width64 += s22_kclock_glyphs[s[i] == ':' ? 10 : s[i] - '0'].adv64;
	pen64 = (kc.cx - kc.x) * 64 - (int)width64 / 2;

	for (i = 0; i < n; i++) {
		const struct s22_kclock_glyph *g =
			&s22_kclock_glyphs[s[i] == ':' ? 10 : s[i] - '0'];
		const u8 *a = s22_kclock_alpha + g->off;
		int gx = DIV_ROUND_CLOSEST(pen64, 64) + g->bx;
		int gy = kc.base - kc.y + g->by;
		int px, py;

		for (py = 0; py < g->h; py++) {
			int ry = gy + py;

			if (ry < 0 || ry >= kc.h)
				continue;
			for (px = 0; px < g->w; px++) {
				int rx = gx + px;
				u32 al = a[py * g->w + px];
				u16 *d;

				if (!al || rx < 0 || rx >= kc.w)
					continue;
				d = &kc.pix[ry * kc.w + rx];
				*d = al == 255 ? kc.color : kc_blend(*d, kc.color, al);
			}
		}
		pen64 += g->adv64;
	}
}

/* kc.pix = the autonomous screen band for a local minute. */
static void kc_render_auto(s64 minute)
{
	kc_render_screen(kc.pix, kc.xres, &kc.lay, minute,
			 READ_ONCE(kc_auto_h24), kc.batt_cap, kc.batt_chg);
}

/* Battery for the autonomous screen; outside kc.lock (charger locks).
 * false: no "battery" supply yet (early boot), try again next tick. */
static bool kc_read_batt(int *cap, bool *chg)
{
	struct power_supply *psy = power_supply_get_by_name("battery");
	union power_supply_propval v;

	*cap = -1;
	*chg = false;
	if (!psy)
		return false;
	if (!power_supply_get_property(psy, POWER_SUPPLY_PROP_CAPACITY, &v))
		*cap = clamp(v.intval, 0, 100);
	if (!power_supply_get_property(psy, POWER_SUPPLY_PROP_STATUS, &v))
		*chg = v.intval == POWER_SUPPLY_STATUS_CHARGING ||
			v.intval == POWER_SUPPLY_STATUS_FULL;
	power_supply_put(psy);
	return true;
}

static bool kc_panel_on(struct spi_panel_data *ctrl)
{
	/* mdss_spi_display_on/off track the MDP5 cover with PANEL_ACTIVE;
	 * PANEL_INIT is only used by the panel event handler. */
	return (ctrl->ctrl_state & CTRL_STATE_PANEL_ACTIVE) &&
		ctrl->panel_data.panel_info.panel_power_state ==
			MDSS_PANEL_POWER_ON;
}

/* Regulators on (also a continuous-splash panel without PANEL_ACTIVE). */
static bool kc_panel_powered(struct spi_panel_data *ctrl)
{
	return ctrl->panel_data.panel_info.panel_power_state !=
		MDSS_PANEL_POWER_OFF;
}

static int kc_cmd(struct spi_panel_data *ctrl, u8 c, u16 a, u16 b, bool args)
{
	int rc;

	kc.cmd[0] = c;
	gpio_direction_output(ctrl->disp_dc_gpio, 0);
	rc = mdss_spi_tx_command(kc.cmd);
	gpio_direction_output(ctrl->disp_dc_gpio, 1);
	if (rc || !args)
		return rc;
	kc.cmd[4] = a >> 8;
	kc.cmd[5] = a & 0xff;
	kc.cmd[6] = b >> 8;
	kc.cmd[7] = b & 0xff;
	return mdss_spi_tx_parameter(kc.cmd + 4, 4);
}

static void kc_restore_window(struct spi_panel_data *ctrl)
{
	kc_cmd(ctrl, KC_CMD_CASET, kc.col0, kc.col1, true);
	kc_cmd(ctrl, KC_CMD_RASET, kc.row0, kc.row1, true);
	kc_cmd(ctrl, KC_CMD_RAMWR, 0, 0, false);
}

/* Caller holds kc.lock and ctrl->spi_tx_mutex, no frame in flight. */
static int kc_send(struct spi_panel_data *ctrl, int x, int y, int w, int h)
{
	int rc;

	rc = kc_cmd(ctrl, KC_CMD_CASET, kc.col0 + x, kc.col0 + x + w - 1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RASET, kc.row0 + y,
			  kc.row0 + y + h - 1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RAMWR, 0, 0, false);
	rc = rc ?: mdss_spi_tx_pixel_sync(kc.pix, w * h * 2);
	/* Frames are bare RAMWR continuations: restore the full window and
	 * leave the write pointer at its start whatever happened above. */
	kc_restore_window(ctrl);
	return rc;
}

/* Same conditions as kc_send(): one full frame (black or Android's last). */
static int kc_send_frame(struct spi_panel_data *ctrl, const void *buf,
			 bool restore)
{
	int rc;

	rc = kc_cmd(ctrl, KC_CMD_CASET, kc.col0, kc.col1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RASET, kc.row0, kc.row1, true);
	rc = rc ?: kc_cmd(ctrl, KC_CMD_RAMWR, 0, 0, false);
	rc = rc ?: mdss_spi_tx_pixel_sync(buf, kc.xres * kc.yres * 2);
	if (restore)
		kc_restore_window(ctrl);
	return rc;
}

static void kc_arm_locked(void)
{
	s64 next;

	if (!kc.ready)
		return;
	alarm_try_to_cancel(&kc.alarm);
	if (!kc.enabled && !kc.own)
		return;
	next = (div_s64(ktime_get_real_seconds(), 60) + 1) * 60 + KC_LAG_S;
	alarm_start(&kc.alarm, ktime_set(next, 0));
}

/* Lit for auto_bl_secs (< 0: until the kernel lets the cover go). */
static void kc_light_locked(void)
{
	int secs = min(READ_ONCE(kc_auto_bl_secs), 3600);

	if (!kc.own || !secs)
		return;
	mdss_spi_s22_cover_bl(1);
	kc.bl_lit = true;
	if (secs > 0) {
		/* stay awake so the off work runs on time, not after resume */
		__pm_wakeup_event(kc.ws_bl, secs * 1000 + 500);
		mod_delayed_work(system_wq, &kc.bl_work, secs * HZ);
	}
}

static void kc_bl_off_fn(struct work_struct *work)
{
	mutex_lock(&kc.lock);
	/* auto_bl_secs < 0 keeps it lit; 0 set while lit turns it off */
	if (kc.own && kc.bl_lit && READ_ONCE(kc_auto_bl_secs) >= 0) {
		mdss_spi_s22_cover_bl(0);
		kc.bl_lit = false;
	}
	mutex_unlock(&kc.lock);
}

static void kc_key_fn(struct work_struct *work)
{
	mutex_lock(&kc.lock);
	if (kc.own) {
		kc.n_keys++;
		kc_light_locked();
	}
	mutex_unlock(&kc.lock);
}

static bool kc_want_locked(void)
{
	return kc_want(kc.ready && kc.ctrl && kc.window_ok &&
		       mdss_spi_client_ready(),
		       READ_ONCE(kc_autonomous), kc.client);
}

/* As mdss_spi_display_on() without Android's frame notifier. */
static int kc_power_on_locked(struct spi_panel_data *ctrl)
{
	struct mdss_panel_data *pdata = &ctrl->panel_data;
	int rc;

	/* never reset or send commands behind a frame still queued */
	mutex_lock(&ctrl->spi_tx_mutex);
	rc = mdss_spi_wait_tx_done(ctrl) ? 0 : -ETIMEDOUT;
	mutex_unlock(&ctrl->spi_tx_mutex);
	rc = rc ?: mdss_spi_panel_power_ctrl(pdata, MDSS_PANEL_POWER_ON);
	if (rc) {
		kc.n_err++;
		pr_err("s22_kclock: cover power on failed %d\n", rc);
		return rc;
	}
	mdss_spi_panel_pinctrl_set_state(ctrl, true);
	mdss_spi_panel_reset(pdata, 1);
	mutex_lock(&ctrl->spi_tx_mutex);
	ctrl->ctrl_state |= CTRL_STATE_PANEL_ACTIVE;
	mdss_spi_panel_on(pdata);
	mutex_unlock(&ctrl->spi_tx_mutex);
	return 0;
}

/* As mdss_spi_display_off(): off cmds only after PANEL_INIT, reset lines
 * and regulators by the lid state.  No frame may be in flight. */
static int kc_power_off_locked(struct spi_panel_data *ctrl)
{
	struct mdss_panel_data *pdata = &ctrl->panel_data;

	mutex_lock(&ctrl->spi_tx_mutex);
	if (!mdss_spi_wait_tx_done(ctrl)) {
		mutex_unlock(&ctrl->spi_tx_mutex);
		kc.n_err++;
		pr_err_ratelimited("s22_kclock: cover busy, not powered off\n");
		return -ETIMEDOUT;
	}
	ctrl->ctrl_state &= ~CTRL_STATE_PANEL_ACTIVE;
	if (ctrl->ctrl_state & CTRL_STATE_PANEL_INIT) {
		mdss_spi_panel_off(pdata);
		ctrl->ctrl_state &= ~CTRL_STATE_PANEL_INIT;
	}
	mutex_unlock(&ctrl->spi_tx_mutex);
	return mdss_spi_panel_power_ctrl(pdata, MDSS_PANEL_POWER_OFF);
}

static void kc_set_active_locked(struct spi_panel_data *ctrl, bool active)
{
	/* the kickoff reads it under spi_tx_mutex */
	mutex_lock(&ctrl->spi_tx_mutex);
	WRITE_ONCE(kc.active, active);
	mutex_unlock(&ctrl->spi_tx_mutex);
}

/* The kernel stops drawing the clock screen (state only). */
static void kc_stop_drawing_locked(void)
{
	if (kc.own)
		kc.n_release++;
	kc.own = false;
	kc.bl_lit = false;
	kc.full_pending = false;
	kc.light_pending = false;
	kc.shown = -1;
	cancel_delayed_work(&kc.bl_work);
}

/* KC_P_ENTER: Android's power, frames and backlight become virtual. */
static void kc_enter_locked(struct spi_panel_data *ctrl)
{
	kc_set_active_locked(ctrl, true);
	mdss_spi_s22_cover_bl_owner(true, false);
	kc.n_enter++;
	pr_info("s22_kclock: kernel owns the cover (no cover app)\n");
}

/*
 * KC_P_LEAVE: a cover app registered (or autonomous=N).  Android on: full
 * power on (reset + on cmds, as mdss_spi_display_on()), Android's last
 * frame (front_buf, kept by the kickoff) and Android's backlight level.
 * Android off: panel off.  On failure the kernel keeps the cover and the
 * next tick retries.
 */
static void kc_leave_locked(struct spi_panel_data *ctrl)
{
	int rc;

	kc_stop_drawing_locked();
	/* still the kernel's: dark through the reset, and if this fails */
	mdss_spi_s22_cover_bl(0);
	if (kc.android_on) {
		rc = kc_power_on_locked(ctrl);
		if (rc)
			return;
		mutex_lock(&ctrl->spi_tx_mutex);
		/* front_buf is only rewritten by a kickoff after this one:
		 * those wait for spi_tx_mutex, and see active == false */
		rc = mdss_spi_wait_tx_done(ctrl) ?
			kc_send_frame(ctrl, ctrl->front_buf, true) : -ETIMEDOUT;
		WRITE_ONCE(kc.active, false);
		mutex_unlock(&ctrl->spi_tx_mutex);
		if (rc) {
			kc.n_err++;
			pr_err("s22_kclock: last frame not sent %d\n", rc);
		}
	} else {
		if (kc_panel_powered(ctrl) && kc_power_off_locked(ctrl))
			return;
		kc_set_active_locked(ctrl, false);
	}
	mdss_spi_s22_cover_bl_owner(false, kc.android_on);
	kc.n_leave++;
	pr_info("s22_kclock: cover handed back to Android (%s)\n",
		kc.android_on ? "on" : "off");
}

/* KC_P_RELEASE: lid open while the kernel owns the cover. */
static void kc_release_locked(struct spi_panel_data *ctrl)
{
	kc_stop_drawing_locked();
	mdss_spi_s22_cover_bl(0);
	if (kc_panel_powered(ctrl))
		kc_power_off_locked(ctrl);
}

/* KC_P_TAKE: lid closed while the kernel owns the cover.  A panel left on
 * by Android (just taken over) is reused as is. */
static int kc_take_locked(struct spi_panel_data *ctrl)
{
	int rc;

	if (!kc_panel_on(ctrl)) {
		rc = kc_power_on_locked(ctrl);
		if (rc)
			return rc;
	}
	kc_layout_auto(kc.yres, &kc.lay);
	kc.own = true;
	kc.shown = -1;
	kc.full_pending = true;
	kc.light_pending = true;
	kc.n_take++;
	return 0;
}

static void kc_tick(void)
{
	struct spi_panel_data *ctrl;
	bool batt_read = false, chg = false;
	int rc, plan, cap = -1;
	u32 now_min;
	s64 minute;

	/* battery at most once a minute, before kc.lock (hint: the kernel
	 * owns or is about to own the cover and the lid is closed) */
	now_min = (u32)div_s64(ktime_get_real_seconds(), 60);
	if ((READ_ONCE(kc.active) || (READ_ONCE(kc_autonomous) &&
				      !READ_ONCE(kc.client))) &&
	    !READ_ONCE(kc.lid_open) && now_min != READ_ONCE(kc.batt_min))
		batt_read = kc_read_batt(&cap, &chg);

	mutex_lock(&kc.lock);
	if (batt_read) {
		kc.batt_cap = cap;
		kc.batt_chg = chg;
		WRITE_ONCE(kc.batt_min, now_min);
	}
	ctrl = kc.ctrl;
	if (!kc.ready || !ctrl)
		goto out;
	plan = kc_plan(kc_want_locked(), kc.android_busy, kc.active,
		       READ_ONCE(kc.lid_open), kc.own, kc_panel_powered(ctrl));
	if (plan & KC_P_ENTER)
		kc_enter_locked(ctrl);
	if (plan & KC_P_LEAVE) {
		kc_leave_locked(ctrl);
		goto out;
	}
	if (plan & KC_P_RELEASE) {
		kc_release_locked(ctrl);
		goto out;
	}
	if ((plan & KC_P_TAKE) && kc_take_locked(ctrl))
		goto out;
	if (!kc.enabled && !kc.own)
		goto out;
	minute = kc_local_minute();
	if (minute == kc.shown && !kc.full_pending) {
		kc.n_same++;
		goto out;
	}
	if (kc.own) {
		kc_render_auto(minute);
	} else if (!kc.bg_valid) {
		kc.n_nobg++;
		goto out;
	} else {
		kc_render(minute);
	}

	mutex_lock(&ctrl->spi_tx_mutex);
	if (!kc_panel_on(ctrl)) {
		kc.n_off++;
		rc = 1;
	} else if (!mdss_spi_wait_tx_done(ctrl)) {
		rc = -ETIMEDOUT;
	} else if (kc.own) {
		rc = kc.full_pending ? kc_send_frame(ctrl, kc.full, false) : 0;
		rc = rc ?: kc_send(ctrl, 0, kc.lay.ay, kc.xres, kc.lay.ah);
	} else {
		rc = kc_send(ctrl, kc.x, kc.y, kc.w, kc.h);
	}
	mutex_unlock(&ctrl->spi_tx_mutex);

	if (!rc) {
		kc.shown = minute;
		kc.full_pending = false;
		kc.n_partial++;
		if (kc.light_pending) {
			kc.light_pending = false;
			kc_light_locked();
		}
	} else if (rc < 0) {
		kc.n_err++;
		pr_err_ratelimited("s22_kclock: partial update failed %d\n", rc);
	}
out:
	kc_arm_locked();
	mutex_unlock(&kc.lock);
}

static void kc_work_fn(struct work_struct *work)
{
	/* Relax first: a tick queued while this one runs keeps the source.
	 * The freezer waits for a running freezable work before suspend. */
	__pm_relax(kc.ws);
	kc_tick();
}

/*
 * Redraws never run in the caller: PM_POST_SUSPEND runs inside pm_suspend()
 * of the suspend HAL thread and the lid in the hall work, and a stuck SPI
 * there blocked suspend, the HAL and system_server (04-10-2026).  The work
 * keeps the wakeup source until it has run; a work already pending relaxes
 * it itself, so a failed queue_work() must not.
 */
static void kc_queue_tick(void)
{
	if (!READ_ONCE(kc.ready))
		return;
	/* inside suspend a held source aborts it; PM_POST_SUSPEND requeues */
	if (!READ_ONCE(kc.suspending))
		__pm_stay_awake(kc.ws);
	/* freezable: runs once devices and the SPI controller are resumed */
	queue_work(system_freezable_wq, &kc.work);
}

static enum alarmtimer_restart kc_alarm_fn(struct alarm *alarm, ktime_t now)
{
	kc.n_alarm++;
	kc_queue_tick();
	return ALARMTIMER_NORESTART;
}

static int kc_pm_notify(struct notifier_block *nb, unsigned long event,
			void *unused)
{
	if (event == PM_SUSPEND_PREPARE) {
		WRITE_ONCE(kc.suspending, true);
	} else if (event == PM_POST_SUSPEND) {
		WRITE_ONCE(kc.suspending, false);
		kc.n_resume++;
		kc_queue_tick();
	}
	return NOTIFY_DONE;
}

void s22_kclock_compose(struct spi_panel_data *ctrl, u16 *frame)
{
	int row;

	if (!READ_ONCE(kc.enabled))
		return;
	mutex_lock(&kc.lock);
	if (kc.ready && kc.enabled && ctrl == kc.ctrl) {
		s64 minute = kc_local_minute();

		for (row = 0; row < kc.h; row++)
			memcpy(kc.bg + row * kc.w,
			       frame + (kc.y + row) * kc.xres + kc.x, kc.w * 2);
		kc.bg_valid = true;
		kc_render(minute);
		for (row = 0; row < kc.h; row++)
			memcpy(frame + (kc.y + row) * kc.xres + kc.x,
			       kc.pix + row * kc.w, kc.w * 2);
		kc.shown = minute;
		kc.n_frames++;
	}
	mutex_unlock(&kc.lock);
}

/* Hall work (and probe): no kc.lock here, it must never wait for SPI. */
void s22_kclock_lid(int open)
{
	WRITE_ONCE(kc.lid_open, !!open);
	/* closed: redraw (client) or take the cover; open: let it go */
	if (!open || READ_ONCE(kc.active) || !READ_ONCE(kc.client))
		kc_queue_tick();
}

/*
 * mdss_spi_display_off()/on(): true = the kernel owns the cover, only
 * Android's view changes and the caller returns 0 without touching the
 * panel.  false = the caller runs its real power sequence and then calls
 * s22_kclock_display_{off,on}_done(); until then ownership does not change.
 */
static bool kc_android_power(struct spi_panel_data *ctrl, bool on)
{
	bool virt;

	mutex_lock(&kc.lock);
	kc.android_on = on;
	kc.android_seen = true;
	virt = kc.active && ctrl == kc.ctrl;
	if (virt) {
		if (on)
			kc.n_von++;
		else
			kc.n_voff++;
	} else {
		kc.android_busy = true;
	}
	mutex_unlock(&kc.lock);
	return virt;
}

static void kc_android_power_done(bool on, int rc)
{
	bool tick;

	mutex_lock(&kc.lock);
	kc.android_busy = false;
	if (rc)		/* mdss_fb keeps the previous power state */
		kc.android_on = !on;
	/* with a cover app never true: the v22c path queues nothing here */
	tick = kc_want_locked() != kc.active;
	mutex_unlock(&kc.lock);
	if (tick)
		kc_queue_tick();
}

bool s22_kclock_display_off(struct spi_panel_data *ctrl)
{
	return kc_android_power(ctrl, false);
}

void s22_kclock_display_off_done(int rc)
{
	kc_android_power_done(false, rc);
}

bool s22_kclock_display_on(struct spi_panel_data *ctrl)
{
	return kc_android_power(ctrl, true);
}

void s22_kclock_display_on_done(int rc)
{
	kc_android_power_done(true, rc);
}

/* Kickoff: drop Android's frame (count it when asked, under spi_tx_mutex). */
bool s22_kclock_swallow(struct spi_panel_data *ctrl, bool count)
{
	if (!READ_ONCE(kc.active) || ctrl != READ_ONCE(kc.ctrl))
		return false;
	if (count)
		kc.n_swallow++;
	return true;
}

/* mdss_spi_client_probe(): the cover SPI device exists now */
void s22_kclock_spi_ready(void)
{
	kc_queue_tick();
}

/* -1: the panel is Android's; 0/1: Android's view while the kernel owns it */
int s22_kclock_android_view(struct spi_panel_data *ctrl)
{
	if (!READ_ONCE(kc.active) || ctrl != READ_ONCE(kc.ctrl))
		return -1;
	return READ_ONCE(kc.android_on);
}

static bool kc_find_window(struct spi_panel_data *ctrl, u8 c, u16 *a, u16 *b)
{
	int i;

	for (i = 0; i < ctrl->on_cmds.cmd_cnt; i++) {
		struct spi_cmd_desc *d = &ctrl->on_cmds.cmds[i];
			const u8 *p = (const u8 *)d->parameter;

		if ((u8)d->command[0] != c || d->dchdr.dlen != 5)
			continue;
		*a = p[0] << 8 | p[1];
		*b = p[2] << 8 | p[3];
		return true;
	}
	return false;
}

void s22_kclock_attach(struct spi_panel_data *ctrl)
{
	struct mdss_panel_info *pinfo = &ctrl->panel_data.panel_info;

	mutex_lock(&kc.lock);
	kc.ctrl = ctrl;
	kc.xres = pinfo->xres;
	kc.yres = pinfo->yres;
	kc.window_ok = pinfo->bpp == 16 &&
		kc_find_window(ctrl, KC_CMD_CASET, &kc.col0, &kc.col1) &&
		kc_find_window(ctrl, KC_CMD_RASET, &kc.row0, &kc.row1) &&
		kc.col1 - kc.col0 + 1 == kc.xres &&
		kc.row1 - kc.row0 + 1 == kc.yres &&
		kc.xres * kc.yres <= 128 * 128 &&
		kc.xres * min(KC_AUTO_H, kc.yres) <= KC_MAX_PIX &&
		ctrl->byte_per_frame == kc.xres * kc.yres * 2;
	mutex_unlock(&kc.lock);
	pr_info("s22_kclock: cover %dx%d window %u-%u/%u-%u %s\n", kc.xres,
		kc.yres, kc.col0, kc.col1, kc.row0, kc.row1,
		kc.window_ok ? "ok" : "unusable");
	kc_queue_tick();
}

static int kc_config_set(const char *val, const struct kernel_param *kp)
{
	int en, x, y, w, h, cx, base, h24;
	unsigned int rgb;
	long long off, next_utc, next_off;
	bool handover;
	int n, rc = 0;

	n = sscanf(val, "%d %d %d %d %d %d %d %d %x %lld %lld %lld", &en, &x,
		   &y, &w, &h, &cx, &base, &h24, &rgb, &off, &next_utc,
		   &next_off);
	if (n < 1)
		return -EINVAL;

	mutex_lock(&kc.lock);
	if (!kc.ready) {
		mutex_unlock(&kc.lock);
		return -EAGAIN;
	}
	/* a cover app is present: the work hands the cover back to Android
	 * (no SPI here) and the autonomous mode is over for good */
	kc.client = true;
	handover = kc.active;
	if (!en) {
		kc.enabled = false;
		goto done;
	}
	if (n != 12 || !kc.ctrl || !kc.window_ok || x < 0 || y < 0 ||
	    w <= 0 || h <= 0 || x + w > kc.xres || y + h > kc.yres ||
	    w * h > KC_MAX_PIX || off < -86400 || off > 86400 ||
	    next_off < -86400 || next_off > 86400) {
		rc = -EINVAL;
		goto unlock;
	}
	if (!kc.enabled || x != kc.x || y != kc.y || w != kc.w || h != kc.h)
		kc.bg_valid = false;	/* wait for a frame with this layout */
	kc.x = x;
	kc.y = y;
	kc.w = w;
	kc.h = h;
	kc.cx = cx;
	kc.base = base;
	kc.h24 = !!h24;
	kc.color = ((rgb >> 8) & 0xf800) | ((rgb >> 5) & 0x07e0) |
		   ((rgb >> 3) & 0x001f);
	kc.off = off;
	kc.next_utc = next_utc;
	kc.next_off = next_off;
	kc.shown = -1;
	kc.enabled = true;
done:
	kc_arm_locked();
unlock:
	mutex_unlock(&kc.lock);
	if (handover)
		kc_queue_tick();
	return rc;
}

static int kc_config_get(char *buf, const struct kernel_param *kp)
{
	int n;

	mutex_lock(&kc.lock);
	n = scnprintf(buf, PAGE_SIZE,
		"%d %d %d %d %d %d %d %d 0x%04x %lld %lld %lld | window %s lid %s bg %d shown %lld | frames %u partial %u same %u nobg %u off %u err %u alarm %u resume %u | auto %s client %d android %s own %d bl %d take %u release %u keys %u tz %d set %lld | active %d busy %d enter %u leave %u von %u voff %u swallow %u batt %d%s\n",
		kc.enabled, kc.x, kc.y, kc.w, kc.h, kc.cx, kc.base, kc.h24,
		kc.color, kc.off, kc.next_utc, kc.next_off,
		kc.window_ok ? "ok" : "unusable",
		READ_ONCE(kc.lid_open) ? "open" : "closed", kc.bg_valid,
		kc.shown, kc.n_frames, kc.n_partial, kc.n_same, kc.n_nobg,
		kc.n_off, kc.n_err, kc.n_alarm, kc.n_resume,
		kc_autonomous ? "on" : "off", kc.client,
		kc.android_on ? "on" : kc.android_seen ? "off" : "unseen",
		kc.own, kc.bl_lit, kc.n_take, kc.n_release, kc.n_keys,
		-sys_tz.tz_minuteswest,
		(long long)READ_ONCE(s22_sys_tz_set), kc.active,
		kc.android_busy, kc.n_enter, kc.n_leave, kc.n_von, kc.n_voff,
		READ_ONCE(kc.n_swallow), kc.batt_cap,
		kc.batt_chg ? " chg" : "");
	mutex_unlock(&kc.lock);
	return n;
}

